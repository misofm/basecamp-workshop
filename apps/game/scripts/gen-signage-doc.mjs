#!/usr/bin/env node
/**
 * Regenerates docs/SIGNAGE.md from the SIGNS table in src/world/signage.ts.
 *
 *   node scripts/gen-signage-doc.mjs          (from apps/game)
 *
 * No TypeScript toolchain needed: it reads the SIGNS object literal with a regex, so
 * keep entries in the `key: { jp: "…", en: "…", note: "…" }` shape (one or several lines).
 */
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("..", import.meta.url).pathname;
const src = readFileSync(`${root}src/world/signage.ts`, "utf8");
const start = src.indexOf("export const SIGNS = {");
const end = src.indexOf("} as const satisfies", start);
if (start < 0 || end < 0) throw new Error("SIGNS block not found in src/world/signage.ts");
const block = src.slice(start, end);

const str = String.raw`"((?:[^"\\]|\\.)*)"`;
const entry = new RegExp(String.raw`(?:^|[\s,{])["']?([A-Za-z_$][\w$]*)["']?\s*:\s*\{\s*jp:\s*${str}\s*,\s*en:\s*${str}\s*(?:,\s*note:\s*${str}\s*)?,?\s*\}`, "g");
const unescape = (s) => (s ?? "").replace(/\\(.)/g, "$1");
const cell = (s) => unescape(s).replace(/\|/g, "\\|").replace(/\n/g, " ");

const rows = [];
for (const m of block.matchAll(entry)) rows.push({ key: m[1], jp: m[2], en: m[3], note: m[4] });
if (rows.length === 0) throw new Error("no SIGNS entries parsed");

const md = `# Signage (Japanese / English)

<!-- GENERATED by scripts/gen-signage-doc.mjs from src/world/signage.ts (SIGNS). Do not edit by hand. -->

> **All Japanese text needs native-speaker review (status: NOT REVIEWED).**
> Nothing here has been checked by a native speaker yet. Until it is, treat every
> Japanese string as a draft (world bible §8.9).

Every sign in the level is bilingual: Japanese on top, English below (or beside), drawn
by \`drawBilingual()\` in \`src/world/signage.ts\` into one shared texture (SignAtlas).
Japanese text lives **only** in \`SIGNS\` (that file); it is rendered with the bundled
subset font \`public/fonts/nozomi-jp-signs.woff2\` (Noto Sans JP Bold, SIL OFL 1.1). After
adding Japanese characters, rebuild the subset with \`scripts/subset-signage-font.sh\`, then
regenerate this page with \`node scripts/gen-signage-doc.mjs\`.

${rows.length} entries.

| Key | Japanese | English | Where / note |
| --- | --- | --- | --- |
${rows.map((r) => `| \`${r.key}\` | ${cell(r.jp)} | ${cell(r.en)} | ${cell(r.note)} |`).join("\n")}

## Rules followed (world bible §8)

- **No real brands, logos, chains, banks or labels.** TriMart, the Triangle Company and
  its mark (\`drawTriangleMark\`) are invented and must not resemble a real company's mark;
  the ATM belongs to no real network; the soup mural is "NOZOMI SOUP", never the real can.
- **No yakuza iconography**: no real crests and no 組 naming (the gang poster uses ギャング).
- **No Rising Sun motifs**, no torii or shrine elements on the street or the shop.
- **No real institutions** on signage (no universities, no real companies).
- **No real artworks** reproduced: murals and posters evoke styles only.
- **Tamashi ads are dystopian satire**, never an endorsement of "plugging in".
- **Money is FakeUSD (FUSD)**, never yen; the counter has no "cash only" sign.
- **No blockchain terms** in any player-visible text.
- **Native-speaker review** of every Japanese string before release (status above).
`;
writeFileSync(`${root}docs/SIGNAGE.md`, md);
console.log(`docs/SIGNAGE.md: ${rows.length} signs`);
